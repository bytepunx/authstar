// Per design/decisions/0101-api-keys.md. A long-lived, programmatic
// credential scoped to a subset of roles its owner (an account or an
// organization) currently holds for one specific application -- shown to
// the caller once, at creation, never again. `grantedRoles` is the
// immutable subset chosen at creation time; this actor never mutates it
// (no `update` command exists, deliberately -- Story text: "cannot be
// edited after creation for now"). The *effective* roles a key actually
// grants at verification time are always re-intersected against the
// owner's *current* roles by `routes/verify-api-key.ts` -- this actor's own
// `grantedRoles` is a ceiling, never assumed to still be a live truth on
// its own.
//
// `grantedRoles` here is plain role-name strings, **not** account's own
// `RoleGrant {name, scope}` shape -- a key is already pinned to exactly one
// `application` (this actor's own field), so a per-role `scope` wrapper
// would be redundant, and it would also disagree with organization's own
// `GrantedRole {application, role}` shape (see organization_actor.ts),
// which has no tenant/application-scope union at all. Normalizing to plain
// strings here means `routes/api-keys.ts`'s subset check and
// `routes/verify-api-key.ts`'s `intersect(apiKey.grantedRoles,
// currentOwnerRolesForApplication)` can both work with the same
// `string[]` shape regardless of which owner kind is involved.
//
// `ownerAccountId`/`ownerOrganizationId` are a flattened, searchable
// projection of `owner` -- a deliberate departure from keep's
// `customer_actor`'s own un-flattened `Scope` convention, because "list my
// (or our) keys" is this feature's primary, frequent operation, not a rare
// one a full-tenant scan-and-filter can absorb.
export interface ApiKeyState {
  apiKeyId: string
  tenant: string
  application: string
  name: string
  owner: { account: string } | { organization: string }
  ownerAccountId: string | null
  ownerOrganizationId: string | null
  grantedRoles: string[]
  createdBy: string
  hashedSecret: string
  salt: string
  secretPreview: string
  status: 'active' | 'revoked'
  createdAt: string
}

interface CreateCommand {
  apiKeyId: string
  tenant: string
  application: string
  name: string
  owner: { account: string } | { organization: string }
  grantedRoles: string[]
  createdBy: string
  hashedSecret: string
  salt: string
  secretPreview: string
}

// Unlike `inviteCode`/`roleDefinition` (caller-chosen composite keys, which
// need a doesNotExist guard against a real duplicate-create race),
// `apiKeyId` is freshly flake-generated by the route before this is ever
// called -- no collision to guard against, same reasoning
// organization_actor.ts's own unguarded `create` already established. A
// plain, unguarded command; consequent calls it with raw state, not the
// `{state, actor}` instance wrapper guarded `{when,then}` pairs receive
// (see role_definition_actor.ts's own header comment on that asymmetry).
function create(_state: ApiKeyState, command: CreateCommand) {
  return {
    type: 'apiKey.created',
    apiKeyId: command.apiKeyId,
    tenant: command.tenant,
    application: command.application,
    name: command.name,
    owner: command.owner,
    grantedRoles: command.grantedRoles,
    createdBy: command.createdBy,
    hashedSecret: command.hashedSecret,
    salt: command.salt,
    secretPreview: command.secretPreview,
  }
}

function isActive(state: ApiKeyState) {
  return state.status === 'active'
}

function revoke() {
  return { type: 'apiKey.revoked' }
}

function rejectRevoke() {
  return Promise.reject(new Error('api key already revoked'))
}

function created(state: ApiKeyState, event: CreateCommand) {
  state.apiKeyId = event.apiKeyId
  state.tenant = event.tenant
  state.application = event.application
  state.name = event.name
  state.owner = event.owner
  state.ownerAccountId = 'account' in event.owner ? event.owner.account : null
  state.ownerOrganizationId = 'organization' in event.owner ? event.owner.organization : null
  state.grantedRoles = event.grantedRoles
  state.createdBy = event.createdBy
  state.hashedSecret = event.hashedSecret
  state.salt = event.salt
  state.secretPreview = event.secretPreview
  state.status = 'active'
  state.createdAt = new Date(0).toISOString() // replaced by consequent's own event timestamp on read
}

function revoked(state: ApiKeyState) {
  state.status = 'revoked'
}

export default function apiKeyActor() {
  return {
    actor: {
      namespace: 'tower',
      type: 'apiKey',
      identifiedBy: 'apiKeyId',
      searchableBy: ['tenant', 'application', 'status', 'ownerAccountId', 'ownerOrganizationId'],
    },
    state: {
      apiKeyId: '',
      tenant: '',
      application: '',
      name: '',
      owner: { account: '' },
      ownerAccountId: null,
      ownerOrganizationId: null,
      grantedRoles: [],
      createdBy: '',
      hashedSecret: '',
      salt: '',
      secretPreview: '',
      status: 'active',
      createdAt: '',
    } satisfies ApiKeyState,
    commands: {
      create,
      revoke: [
        { when: isActive, then: revoke },
        rejectRevoke,
      ],
    },
    events: {
      created,
      revoked,
    },
  }
}
